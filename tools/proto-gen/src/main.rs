fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    let check = match args.as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            eprintln!("usage: proto-gen [--check]");
            return ExitCode::from(2);
        }
    };
    match run(check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("proto-gen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(check: bool) -> Result<(), Box<dyn std::error::Error>> {
    let work = env::temp_dir().join(format!("proto-gen-{}", std::process::id()));
    let _ = fs::remove_dir_all(&work);
    fs::create_dir_all(&work)?;
    let descriptors = work.join("descriptors.bin");
    let roots: Vec<PathBuf> = ROOTS.iter().map(|r| Path::new(INCLUDE).join(r)).collect();
    prost_build::Config::new()
        .out_dir(&work)
        .file_descriptor_set_path(&descriptors)
        .enable_type_names()
        .disable_comments(["."])
        .compile_protos(&roots, &[INCLUDE])?;
    let set = FileDescriptorSet::decode(fs::read(&descriptors)?.as_slice())?;
    fs::remove_file(&descriptors)?;
    fs::write(work.join("schema.rs"), render_schema(&set)?)?;

    let mut generated = BTreeMap::new();
    for entry in fs::read_dir(&work)? {
        let path = entry?.path();
        let name = path.file_name().unwrap().to_string_lossy().into_owned();
        generated.insert(name, format!("{HEADER}{}", fs::read_to_string(&path)?));
    }
    fs::remove_dir_all(&work)?;

    let mut existing = BTreeMap::new();
    if let Ok(entries) = fs::read_dir(OUTPUT) {
        for entry in entries {
            let path = entry?.path();
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            existing.insert(name, fs::read_to_string(&path)?);
        }
    }
    if check {
        if existing != generated {
            let names: Vec<_> = generated
                .keys()
                .chain(existing.keys())
                .filter(|n| generated.get(*n) != existing.get(*n))
                .collect();
            return Err(format!("{OUTPUT} is out of date: {names:?}").into());
        }
        println!("proto-gen: {OUTPUT} matches ({} files)", generated.len());
        return Ok(());
    }
    let _ = fs::remove_dir_all(OUTPUT);
    fs::create_dir_all(OUTPUT)?;
    for (name, text) in &generated {
        fs::write(Path::new(OUTPUT).join(name), text)?;
    }
    println!("proto-gen: wrote {} files to {OUTPUT}", generated.len());
    Ok(())
}

fn collect(prefix: &str, message: &DescriptorProto, out: &mut BTreeMap<String, DescriptorProto>) {
    let name = format!("{prefix}.{}", message.name());
    for nested in &message.nested_type {
        collect(&name, nested, out);
    }
    out.insert(name, message.clone());
}

fn render_schema(set: &FileDescriptorSet) -> Result<String, String> {
    let mut messages = BTreeMap::new();
    for file in &set.file {
        for message in &file.message_type {
            collect(file.package(), message, &mut messages);
        }
    }
    let mut out = String::from(
        "/// Every message in the generated closure, sorted by full name.\n\
         pub static MESSAGES: &[MessageSchema] = &[\n",
    );
    for (name, message) in &messages {
        let _ = writeln!(
            out,
            "    MessageSchema {{\n        name: {name:?},\n        fields: &["
        );
        let mut fields = message.field.clone();
        fields.sort_by_key(|f| f.number());
        for field in fields {
            let kind = match field.r#type() {
                Type::Int32
                | Type::Int64
                | Type::Uint32
                | Type::Uint64
                | Type::Sint32
                | Type::Sint64
                | Type::Bool
                | Type::Enum => "Kind::Varint".to_owned(),
                Type::Fixed64 | Type::Sfixed64 | Type::Double => "Kind::Fixed64".to_owned(),
                Type::Fixed32 | Type::Sfixed32 | Type::Float => "Kind::Fixed32".to_owned(),
                Type::String | Type::Bytes => "Kind::Bytes".to_owned(),
                Type::Message => {
                    let target = field.type_name().trim_start_matches('.');
                    if !messages.contains_key(target) {
                        return Err(format!(
                            "{name}.{} references unknown {target}",
                            field.name()
                        ));
                    }
                    format!("Kind::Message({target:?})")
                }
                Type::Group => return Err(format!("{name}.{} is a group", field.name())),
            };
            let _ = writeln!(
                out,
                "            Field {{ number: {}, name: {:?}, required: {}, repeated: {}, kind: {kind} }},",
                field.number(),
                field.name(),
                field.label() == Label::Required,
                field.label() == Label::Repeated,
            );
        }
        let _ = writeln!(out, "        ],\n    }},");
    }
    out.push_str("];\n");
    Ok(out)
}
