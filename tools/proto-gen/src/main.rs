//! Generates `core/aap-proto/src/generated/` from the vendored open-android-auto subset:
//! prost message types, plus a schema table of every field's number, label, and wire
//! kind so that required proto2 fields can be checked on the wire (prost itself decodes a
//! missing required field as its default). `--check` compares with the checked-in files
//! instead of writing them. Run through `tools/proto-gen.sh`, which supplies the pinned
//! protoc.
use prost::Message;
use prost_types::{
    field_descriptor_proto::{Label, Type},
    DescriptorProto, FileDescriptorSet,
};
use std::{
    collections::BTreeMap,
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
};

const INCLUDE: &str = "protocol/upstream/open-android-auto";
const OUTPUT: &str = "core/aap-proto/src/generated";
